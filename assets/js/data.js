(function initRoyaScrollLayoutSync() {
  function syncScrollTriggersAfterLayout() {
    document.querySelectorAll('.wa-card').forEach((card) => {
      if (typeof gsap !== 'undefined') {
        gsap.set(card, { opacity: 1, visibility: 'visible', clearProps: 'opacity,visibility' });
      } else {
        card.style.opacity = '1';
        card.style.visibility = 'visible';
      }
    });
    if (typeof ScrollTrigger !== 'undefined') {
      ScrollTrigger.refresh();
      requestAnimationFrame(() => ScrollTrigger.refresh());
    }
  }

  function initWaCardVisibilityGuard() {
    const grid = document.querySelector('.wa-grid');
    if (!grid || !('IntersectionObserver' in window)) return;
    const observer = new IntersectionObserver((entries) => {
      if (entries.some((entry) => entry.isIntersecting)) syncScrollTriggersAfterLayout();
    }, { threshold: 0, rootMargin: '0px 0px 10% 0px' });
    observer.observe(grid);
  }

  let waCardGuardReady = false;

  window.royaSyncScrollLayout = function royaSyncScrollLayout() {
    syncScrollTriggersAfterLayout();
    if (!waCardGuardReady) {
      waCardGuardReady = true;
      initWaCardVisibilityGuard();
    }
  };

  window.addEventListener('load', syncScrollTriggersAfterLayout, { once: true, passive: true });
})();
